#!/usr/bin/python3
"""Maintainer tool for regolith-sway-screen-reader's Orca key map and sway bindings.

  orca-keymap.py dump OUT.json
      Write Orca's default desktop key bindings and the remote-controller command
      behind each one, read from the installed Orca (49 or 50; run it in a session
      with Orca's Python modules importable). Used to refresh
      usr/share/regolith/sway/screen-reader/orca-keymap.json for a new Orca release.

  orca-keymap.py sway KEYMAP.json OUT.conf
      Write the sway bindings partial (usr/share/regolith/sway/screen-reader/orca.conf)
      from the key map. tests/check-sway-screen-reader.sh checks that the shipped
      partial is what this writes.

Key map format: {"orca": VERSION, "desktop": {BINDING: {"module", "method", "command",
"group"}}}. BINDING is Orca's own notation ("Orca+t", "Orca+t x2", "KP_Up",
"Orca+Shift+KP_Up"). "module" and "method" are empty when the command is not on
Orca's remote controller.
"""
import json
import sys

ORCA_KEYS = ("Insert", "KP_Insert")
MODS = {"Shift": "Shift", "Ctrl": "Ctrl", "Alt": "Mod1"}
# Keys whose Orca command is served another way than "regolith-orcactl key".
OVERRIDES = {
    "Orca+h": "exec regolith-orcactl prompt --learn",  # learn mode, reimplemented in the prompt
    "Orca+space": "exec regolith-orcactl prefs",  # org.gnome.Orca.Service.ShowPreferences
}
# Orca+p and Orca+b are free in Orca's desktop layout; Regolith uses them for the
# prompt and for the browse-keys mode.
EXTRA = {
    "Orca+p": "exec regolith-orcactl prompt",
    "Orca+b": "mode orca-browse",
}
# Bare keys that only make sense while Orca drives the caret (browse mode); they go
# into a mode the user enters with Orca+b.
BROWSE_GROUPS = {"Structural navigation", "Caret navigation", "Table navigation"}


def sway_combo(binding, orca_key):
    mods, keys = [], []
    for part in binding.split("+"):
        if part == "Orca":
            keys.append(orca_key)
        elif part in MODS:
            mods.append(MODS[part])
        else:
            keys.append(part)
    return "+".join(mods + keys)


def sway_conf(keymap):
    km = keymap["desktop"]
    for binding in EXTRA:
        if binding in km:
            raise SystemExit(f"{binding} is bound by Orca {keymap['orca']}; pick another key")
    chords, bare, browse = [], [], []
    for binding, entry in sorted(km.items()):
        if " x" in binding:
            continue  # regolith-orcactl turns a quick second press into the x2/x3 command
        if binding in OVERRIDES:
            action = OVERRIDES[binding]
        elif entry["module"]:
            action = f"exec regolith-orcactl key {binding}"
        else:
            continue  # not on the remote controller: leave the key to the application
        if binding.startswith("Orca+"):
            chords.append((binding, action))
        elif entry["group"] in BROWSE_GROUPS:
            browse.append((binding, action))
        else:
            bare.append((binding, action))
    chords += sorted(EXTRA.items())
    chords.sort()

    out = [
        f"# Generated by tests/orca-keymap.py from Orca {keymap['orca']}'s default desktop key map.",
        "# Do not include this file from a sway config: regolith-sway-screen-reader applies it",
        "# over IPC while the screen reader is on and Orca's remote controller is running,",
        "# and removes it again when either stops.",
        "#",
        "# The Orca key is Insert or keypad Insert (Num Lock off). Orca+key chords and the",
        "# keypad keys run Orca's command through regolith-orcactl, so the key never reaches",
        "# the focused application.",
        "",
        "# The Orca key on its own: keep it from the application.",
    ]
    for key in ORCA_KEYS:
        out.append(f"bindsym --no-repeat {key} nop orca key")
    out += ["", "# Orca+key chords"]
    for binding, action in chords:
        for key in ORCA_KEYS:
            out.append(f"bindsym --no-repeat {sway_combo(binding, key)} {action}")
    out += ["", "# Keypad review, where am I and say all"]
    for binding, action in bare:
        out.append(f"bindsym --no-repeat {sway_combo(binding, 'Insert')} {action}")
    out += [
        "",
        "# Browse keys: Orca's structural, caret and table navigation keys. Orca+b enters",
        "# the mode, Orca+b or Escape leaves it; regolith-sway-screen-reader announces both.",
        "mode orca-browse {",
    ]
    for key in ORCA_KEYS:
        out.append(f"    bindsym --no-repeat {key}+b mode default")
    out.append("    bindsym --no-repeat Escape mode default")
    for binding, action in browse:
        out.append(f"    bindsym {sway_combo(binding, 'Insert')} {action}")
    out += [
        "}",
        "",
        "# While the prompt (regolith-orcactl prompt) is open, sway is in this empty mode, so",
        "# that chords reach the prompt instead of the bindings above. Ctrl+Alt+Escape is",
        "# the way out if the prompt ever fails to switch back.",
        "mode orca-prompt {",
        "    bindsym Ctrl+Mod1+Escape mode default",
        "}",
    ]
    return "\n".join(out) + "\n"


def dump():
    import gi

    gi.require_version("Atspi", "2.0")
    gi.require_version("Gtk", "3.0")
    from orca import command_manager, dbus_service, debug, keybindings, orca_platform
    from orca.scripts import default

    debug.debugLevel = debug.LEVEL_SEVERE
    script = default.Script(None)  # registers every keyboard command
    del script
    ctrl = dbus_service.get_remote_controller()
    owners = {id(inst): name for name, inst in getattr(ctrl, "_pending_registrations", {}).items()}

    def notation(kb):
        if kb is None:
            return ""
        mods = []
        if kb.modifiers & keybindings.ORCA_MODIFIER_MASK:
            mods.append("Orca")
        for bit, name in ((0, "Shift"), (2, "Ctrl"), (3, "Alt")):
            if kb.modifiers & (1 << bit):
                mods.append(name)
        clicks = f" x{kb.click_count}" if getattr(kb, "click_count", 1) > 1 else ""
        return "+".join(mods + [kb.keysymstring]) + clicks

    desktop = {}
    for cmd in command_manager.get_manager().get_all_keyboard_commands():
        binding = notation(cmd.get_default_keybinding(True))
        if not binding:
            continue
        fn = cmd.get_function()
        owner = getattr(fn, "__self__", None)
        module = owners.get(id(owner), "") if owner is not None else ""
        method = "".join(p.capitalize() for p in fn.__name__.split("_"))
        on_dbus = bool(module) and hasattr(fn, "dbus_command_description")
        desktop.setdefault(binding, {
            "module": module if on_dbus else "",
            "method": method if on_dbus else "",
            "command": cmd.get_name(),
            "group": cmd.get_group_label() if hasattr(cmd, "get_group_label") else "",
        })
    return {"orca": orca_platform.version, "desktop": desktop}


def main(argv):
    if len(argv) == 2 and argv[0] == "dump":
        with open(argv[1], "w", encoding="utf-8") as fh:
            json.dump(dump(), fh, indent=1, sort_keys=True)
            fh.write("\n")
    elif len(argv) == 3 and argv[0] == "sway":
        with open(argv[1], encoding="utf-8") as fh:
            keymap = json.load(fh)
        with open(argv[2], "w", encoding="utf-8") as fh:
            fh.write(sway_conf(keymap))
    else:
        sys.stderr.write(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
